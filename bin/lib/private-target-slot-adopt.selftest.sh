#!/usr/bin/env bash
# private-target-slot-adopt.selftest.sh — warm reuse of a dead private Cargo root
# must never MOVE it (WI-10004841).
#
# claim-target-dir.sh lets an overflow launch adopt the newest dead private target
# root as a warm cache (WI-10004764). The first version adopted by `mv -T`, but a
# Cargo root is not relocatable: Cargo keeps a finished build script's output when
# the root moves, and tauri's OUT_DIR permission listings hold ABSOLUTE paths into
# the old root. Every adopted root then failed `tauri dev` with "failed to read
# plugin permissions … No such file or directory". Hermetic (temp HOME, temp roots,
# no cargo, no network), it proves:
#   1. adoption keeps the root at its own path, so the paths its build scripts
#      wrote still resolve, and holds that root's own lock;
#   2. a root an older reaper already moved (root-output outside the root) is
#      reaped, never adopted;
#   3. the overflow claim hands fd 8, the descriptor the launch inherits, to the
#      adopted root's lock and exports that root as CARGO_TARGET_DIR.
#
#   bash bin/lib/private-target-slot-adopt.selftest.sh     # exit 0 = PASS, 1 = FAIL
#
# PAPERCUSP_SELFTEST_CLAIM_TARGET_DIR=<path> tests another copy of
# claim-target-dir.sh (its siblings must sit beside it); that is how the guard is
# shown to fail against the pre-fix implementation.
set -uo pipefail
DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
SUBJECT="${PAPERCUSP_SELFTEST_CLAIM_TARGET_DIR:-$DIR/claim-target-dir.sh}"

command -v flock >/dev/null 2>&1 || { echo "SKIP: flock unavailable"; exit 0; }
command -v node >/dev/null 2>&1 || { echo "SKIP: node unavailable (reference probe)"; exit 0; }

FAILS=0
ok()  { echo "  ✓ $*"; }
bad() { echo "  ✗ $*"; FAILS=$((FAILS + 1)); }

WORK="$(mktemp -d /tmp/private-slot-adopt-selftest.XXXXXX)" || exit 1
HOLDER_PID=""
cleanup() {
  [[ -n "$HOLDER_PID" ]] && kill "$HOLDER_PID" 2>/dev/null
  rm -rf -- "$WORK"
}
trap cleanup EXIT

export HOME="$WORK/home"
export PAPERCUSP_RELEASE_RETENTION_ROOT="$WORK/retention"
export PAPERCUSP_RELEASE_DELETION_AUDIT_PATH="$WORK/retention/deletion-audit.tsv"
export PAPERCUSP_DESKTOP_REAP_ONLY=1
export PAPERCUSP_DESKTOP_PRIVATE_SLOT_REAP_SYNC=1
export PAPERCUSP_DESKTOP_PRIVATE_SLOT_GRACE_SEC=0
unset CARGO_TARGET_DIR PAPERCUSP_DESKTOP_PRIVATE_SLOT_REAP PAPERCUSP_DESKTOP_PRIVATE_SLOT_REAP_DRY_RUN
mkdir -p "$HOME" "$PAPERCUSP_RELEASE_RETENTION_ROOT"

# shellcheck source=claim-target-dir.sh
source "$SUBJECT"
set +e
mkdir -p "$__pc_slot_lockdir"

SHARED="$WORK/cargo-target"
SLOTS="$SHARED/.papercusp-target-slots"
mkdir -p "$SLOTS"

# make_root <dir> <recorded-root>: a minimal Cargo root whose tauri build script
# ran with its OUT_DIR under <recorded-root>, listing one permission file by
# absolute path, as tauri's `tauri-core-*-permission-files` does.
make_root() {
  local dir="$1" recorded="$2" build out
  build="$dir/debug/build/tauri-0000000000000000"
  out="$build/out"
  mkdir -p "$out/permissions/app/autogenerated/commands"
  printf '%s\n' "$recorded/debug/build/tauri-0000000000000000/out" > "$build/root-output"
  : > "$out/permissions/app/autogenerated/commands/app_hide.toml"
  printf '["%s"]' "$recorded/debug/build/tauri-0000000000000000/out/permissions/app/autogenerated/commands/app_hide.toml" \
    > "$out/tauri-core-app-permission-files"
  # A legacy-free root: its lock file exists and nobody holds it (a dead claimant).
  : > "$__pc_slot_lockdir/${dir##*/}.lock"
}

# listed_file_exists <dir>: does the permission file the listing names resolve?
listed_file_exists() {
  local listing="$1/debug/build/tauri-0000000000000000/out/tauri-core-app-permission-files" path
  [[ -f "$listing" ]] || return 1
  path="$(sed -e 's/^\["//' -e 's/"\]$//' "$listing")"
  [[ -f "$path" ]]
}

lock_is_held() { ! ( exec 6>>"$1" && flock -n 6 ) 2>/dev/null; }

echo "1. adoption keeps a dead root at its own path"
ROOT_A="$SLOTS/pid999911"
make_root "$ROOT_A" "$ROOT_A"
(
  __pc_reap_private_target_slots "$SHARED" "pid999901"
  if [[ "$__pc_adopted_private_root" == "$ROOT_A" ]]; then ok "adopted root is the dead root's own path"
  else echo "  ✗ adopted '$__pc_adopted_private_root', expected '$ROOT_A'"; exit 1; fi
  [[ -d "$ROOT_A" ]] || { echo "  ✗ the adopted root no longer exists at its path"; exit 1; }
  if listed_file_exists "$ROOT_A"; then ok "the absolute path its build script wrote still resolves"
  else echo "  ✗ the permission listing now points at a missing file (the WI-10004841 failure)"; exit 1; fi
  if [[ "${__pc_adopted_private_lock_fd:-}" =~ ^[0-9]+$ ]] && lock_is_held "$__pc_slot_lockdir/pid999911.lock"; then
    ok "the adopter holds the root's own lock"
  else echo "  ✗ the adopted root's lock is not held"; exit 1; fi
) || FAILS=$((FAILS + 1))
rm -rf -- "$ROOT_A"; rm -f -- "$__pc_slot_lockdir"/pid99991*.lock

echo "2. a root an older reaper moved is reaped, not adopted"
ROOT_B="$SLOTS/pid999912"
make_root "$ROOT_B" "$SLOTS/pid999900"
(
  __pc_reap_private_target_slots "$SHARED" "pid999902"
  if [[ -z "$__pc_adopted_private_root" ]]; then ok "the relocated root was not adopted"
  else echo "  ✗ adopted a relocated root: $__pc_adopted_private_root"; exit 1; fi
  if [[ ! -e "$ROOT_B" ]]; then ok "the relocated root was reaped"
  else echo "  ✗ the relocated root is still present"; exit 1; fi
) || FAILS=$((FAILS + 1))
rm -rf -- "$ROOT_B" "$SLOTS"/.reaping-*

echo "3. the overflow claim hands fd 8 to the adopted root's lock"
ROOT_C="$SLOTS/pid999913"
make_root "$ROOT_C" "$ROOT_C"
flock "$__pc_slot_lockdir/slot0.lock" sleep 60 &
HOLDER_PID=$!
for _ in $(seq 1 50); do lock_is_held "$__pc_slot_lockdir/slot0.lock" && break; sleep 0.1; done
(
  __pc_cargo_target_root() { printf '%s' "$SHARED"; }
  PAPERCUSP_DESKTOP_TARGET_SLOTS=1 __pc_claim_target_dir 2>/dev/null || { echo "  ✗ claim failed"; exit 1; }
  if [[ "${CARGO_TARGET_DIR:-}" == "$ROOT_C" ]]; then ok "CARGO_TARGET_DIR is the adopted root, unmoved"
  else echo "  ✗ CARGO_TARGET_DIR='${CARGO_TARGET_DIR:-}', expected '$ROOT_C'"; exit 1; fi
  fd8="$(readlink "/proc/$BASHPID/fd/8" 2>/dev/null)"
  if [[ "$fd8" == "$__pc_slot_lockdir/pid999913.lock" ]] && lock_is_held "$fd8"; then
    ok "fd 8 holds the adopted root's lock"
  else echo "  ✗ fd 8 is '$fd8', expected the held lock $__pc_slot_lockdir/pid999913.lock"; exit 1; fi
  if [[ ! -e "$__pc_slot_lockdir/pid$BASHPID.lock" && ! -e "$__pc_slot_lockdir/pid$$.lock" ]]; then
    ok "the unused per-pid lock file was removed"
  else echo "  ✗ the unused per-pid lock file was left behind"; exit 1; fi
) || FAILS=$((FAILS + 1))

if ((FAILS > 0)); then echo "FAIL ($FAILS case(s))"; exit 1; fi
echo "PASS"
exit 0
